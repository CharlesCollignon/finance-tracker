import { useState } from "react";
import {
  ActivityIndicator,
  FlatList,
  Pressable,
  RefreshControl,
  View,
} from "react-native";
import { useRouter, type Href } from "expo-router";
import { Ionicons } from "@expo/vector-icons";
import * as WebBrowser from "expo-web-browser";
import Animated, {
  FadeInDown,
  useReducedMotion,
} from "react-native-reanimated";

import {
  ENTRAIDE_FILTERS,
  ENTRAIDE_HREF,
  type EntraideFilter,
  type EntraidePostSummary,
  type EntraideSort,
} from "@finance/core/entraide";
import { entraideCopyFor, entraideWhen } from "@finance/core/entraide-copy";
import { DURATION, STAGGER_STEP_MS } from "@finance/core/motion";

import { PostCard } from "@/components/entraide/PostCard";
import { ScreenError } from "@/components/ScreenError";
import { ChipRow } from "@/components/ui/ChipRow";
import { Screen } from "@/components/ui/Screen";
import { SegmentedControl } from "@/components/ui/SegmentedControl";
import { ScreenSkeleton } from "@/components/ui/Skeleton";
import { Text } from "@/components/ui/Text";
import { useRefreshable } from "@/hooks/useRefreshable";
import { PAGE, readList } from "@/lib/entraide";
import { WEB_APP_URL } from "@/lib/env";
import { hapticLight } from "@/lib/haptics";
import { useLocale } from "@/providers/LocaleProvider";
import { ICON } from "@/theme/tokens";
import { useThemeColors } from "@/theme/useThemeColors";

/** Past this, a card waits no longer to rise than the eighth did. */
const STAGGER_CAP = 8;

interface MorePages {
  key: string;
  posts: EntraidePostSummary[];
  done: boolean;
}

/**
 * Entraide on the phone: the questions and shares people using Pluclair
 * ask each other, newest activity first or the most useful, and the way to
 * ask one. Read as on the site, from the same tables; a filter re-deals
 * the cards, which rise a beat apart, and the list grows as it is scrolled.
 */
export default function EntraideScreen() {
  const locale = useLocale();
  const copy = entraideCopyFor(locale);
  const router = useRouter();
  const colors = useThemeColors();
  const reduceMotion = useReducedMotion();
  const [filter, setFilter] = useState<EntraideFilter>("all");
  const [sort, setSort] = useState<EntraideSort>("recent");
  const listKey = `${filter}:${sort}`;

  const { data, error, loading, refreshing, onRefresh } = useRefreshable(
    async () => ({
      posts: await readList(filter, sort, 0),
      readAt: new Date(),
    }),
    [filter, sort],
    { reads: ["community"] },
  );

  // The pages past the first, for the filter and order they were read for.
  const [more, setMore] = useState<MorePages>({
    key: listKey,
    posts: [],
    done: false,
  });
  const [loadingMore, setLoadingMore] = useState(false);
  const pages =
    more.key === listKey ? more : { key: listKey, posts: [], done: false };
  const first = data?.posts ?? [];
  const firstIds = new Set(first.map((post) => post.id));
  // A page read before a refresh may repeat what the first page now holds.
  const posts = [
    ...first,
    ...pages.posts.filter((post) => !firstIds.has(post.id)),
  ];
  const done = first.length < PAGE || pages.done;

  async function loadMore() {
    if (loading || loadingMore || done) {
      return;
    }
    setLoadingMore(true);
    const next = await readList(
      filter,
      sort,
      first.length + pages.posts.length,
    ).catch(() => null);
    setLoadingMore(false);
    if (next) {
      setMore({
        key: listKey,
        posts: [...pages.posts, ...next],
        done: next.length < PAGE,
      });
    }
  }

  function refresh() {
    setMore({ key: listKey, posts: [], done: false });
    onRefresh();
  }

  const header = (
    <View className="gap-4 pb-2">
      <Text variant="muted" className="leading-5">
        {copy.hero.intro}
      </Text>
      {WEB_APP_URL ? (
        <Pressable
          accessibilityRole="link"
          onPress={() =>
            void WebBrowser.openBrowserAsync(
              `${WEB_APP_URL}${ENTRAIDE_HREF}/regles`,
            )
          }
          className="min-h-11 flex-row items-center gap-1.5 self-start"
        >
          <Ionicons
            name="book-outline"
            size={ICON.md}
            color={colors.foreground}
          />
          <Text className="text-sm underline">{copy.hero.rules}</Text>
        </Pressable>
      ) : null}

      {/* The way to ask: an empty field, the one gold thing on the screen. */}
      <Pressable
        accessibilityRole="button"
        accessibilityLabel={copy.composer.pill}
        onPress={() => {
          void hapticLight();
          // Cast while the typed routes are generated by the dev server.
          router.push("/entraide/new" as Href);
        }}
        className="min-h-14 flex-row items-center gap-3 rounded-full border border-border bg-background pl-5 pr-2 active:bg-card"
      >
        <Text variant="muted" className="flex-1 text-base">
          {copy.composer.pill}
        </Text>
        <View className="h-10 w-10 items-center justify-center rounded-full border border-primary-rim bg-primary">
          <Ionicons name="add" size={ICON.xl} color={colors.primaryForeground} />
        </View>
      </Pressable>

      <ChipRow
        label={copy.filters.label}
        options={ENTRAIDE_FILTERS.map((value) => ({
          value,
          label: copy.filters[value],
        }))}
        value={filter}
        onChange={setFilter}
      />
      <SegmentedControl
        label={copy.sorts.label}
        segments={[
          { value: "recent", label: copy.sorts.recent },
          { value: "useful", label: copy.sorts.useful },
        ]}
        value={sort}
        onChange={setSort}
      />
    </View>
  );

  return (
    <Screen
      title={copy.hero.title}
      back={{
        label: copy.list.back,
        onPress: () =>
          router.canGoBack() ? router.back() : router.replace("/" as Href),
      }}
      showRefresh={false}
      className="px-0 py-0"
    >
      {loading && !data ? (
        <View className="px-4 py-4">
          {header}
          <ScreenSkeleton rows={3} />
        </View>
      ) : error && !data ? (
        <View className="flex-1 justify-center px-4">
          <ScreenError message={error} onRetry={onRefresh} />
        </View>
      ) : (
        <FlatList
          // A new filter or order deals the cards again.
          key={listKey}
          data={posts}
          keyExtractor={(post) => String(post.id)}
          ListHeaderComponent={header}
          contentContainerClassName="gap-3 px-4 pb-24 pt-4"
          renderItem={({ item, index }) => (
            <Animated.View
              entering={
                reduceMotion
                  ? undefined
                  : FadeInDown.duration(DURATION.enter).delay(
                      Math.min(index % PAGE, STAGGER_CAP) * STAGGER_STEP_MS,
                    )
              }
            >
              <PostCard
                post={item}
                when={entraideWhen(
                  item.lastActivityAt,
                  data?.readAt ?? new Date(0),
                  locale,
                )}
                copy={copy}
                onOpen={() =>
                  // Cast while the typed routes are generated by the dev server.
                  router.push(`/entraide/${item.id}` as Href)
                }
              />
            </Animated.View>
          )}
          ListEmptyComponent={
            <View className="rounded-card border border-border bg-card/70 p-card">
              <Text variant="muted">
                {filter === "all" ? copy.list.empty : copy.list.emptyFiltered}
              </Text>
            </View>
          }
          ListFooterComponent={
            loadingMore ? (
              <ActivityIndicator
                accessibilityLabel={copy.list.more}
                color={colors.mutedForeground}
                className="py-4"
              />
            ) : null
          }
          onEndReached={() => void loadMore()}
          onEndReachedThreshold={0.5}
          refreshControl={
            <RefreshControl
              refreshing={refreshing}
              onRefresh={refresh}
              tintColor={colors.mutedForeground}
            />
          }
          showsVerticalScrollIndicator={false}
        />
      )}
    </Screen>
  );
}
