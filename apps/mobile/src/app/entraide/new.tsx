import { useEffect, useState } from "react";
import {
  KeyboardAvoidingView,
  Platform,
  Pressable,
  ScrollView,
  View,
} from "react-native";
import { useRouter, type Href } from "expo-router";
import { Ionicons } from "@expo/vector-icons";
import * as WebBrowser from "expo-web-browser";
import Animated, {
  FadeInDown,
  FadeOut,
  useReducedMotion,
} from "react-native-reanimated";

import {
  ENTRAIDE_HREF,
  ENTRAIDE_LIMITS,
  type EntraideMatch,
  type PostKind,
} from "@finance/core/entraide";
import {
  countWords,
  entraideCopyFor,
  entraideErrorText,
} from "@finance/core/entraide-copy";
import { DURATION, STAGGER_STEP_MS } from "@finance/core/motion";

import { HandleField, handleReady } from "@/components/entraide/HandleField";
import { MaskNotice } from "@/components/entraide/Notices";
import { Button } from "@/components/ui/Button";
import { Input } from "@/components/ui/Input";
import { Screen } from "@/components/ui/Screen";
import { SegmentedControl } from "@/components/ui/SegmentedControl";
import { Text } from "@/components/ui/Text";
import { readMyHandle, searchAsked, writeEntraide } from "@/lib/entraide";
import { WEB_APP_URL } from "@/lib/env";
import { hapticSelection, hapticSuccess } from "@/lib/haptics";
import { useAuth } from "@/providers/AuthProvider";
import { useLocale } from "@/providers/LocaleProvider";
import { ICON } from "@/theme/tokens";
import { useThemeColors } from "@/theme/useThemeColors";

/** How long the title rests before « Déjà demandé ? » looks. */
const SEARCH_AFTER_MS = 450;

/**
 * A new question or share: what kind, the title, the details if any, and
 * the pseudonym the first time. While a question's title is typed, the
 * threads that already ask it slide in under it (« Déjà demandé ? »); what
 * will be masked is said before anything goes. Published, it opens as its
 * own thread.
 */
export default function NewEntraidePostScreen() {
  const locale = useLocale();
  const copy = entraideCopyFor(locale);
  const words = copy.composer;
  const router = useRouter();
  const colors = useThemeColors();
  const reduceMotion = useReducedMotion();
  const { user } = useAuth();
  const userId = user?.id ?? null;

  const [kind, setKind] = useState<PostKind>("question");
  const [title, setTitle] = useState("");
  const [body, setBody] = useState("");
  const [typed, setTyped] = useState("");
  const [handle, setHandle] = useState<string | null>(null);
  const [handleRead, setHandleRead] = useState(false);
  const [matches, setMatches] = useState<EntraideMatch[]>([]);
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!userId) {
      return;
    }
    let live = true;
    void readMyHandle(userId).then((mine) => {
      if (live) {
        setHandle(mine);
        setHandleRead(true);
      }
    });
    return () => {
      live = false;
    };
  }, [userId]);

  // « Déjà demandé ? »: once the title has rested, ask what is close to it.
  const query = title.trim();
  const searching = kind === "question" && query.length >= 12;
  useEffect(() => {
    if (!searching) {
      return;
    }
    let live = true;
    const timer = setTimeout(() => {
      void searchAsked(query).then((found) => {
        if (live) {
          setMatches(found);
        }
      });
    }, SEARCH_AFTER_MS);
    return () => {
      live = false;
      clearTimeout(timer);
    };
  }, [searching, query]);
  const shownMatches = searching ? matches : [];

  const titleLength = title.trim().length;
  const ready =
    titleLength >= ENTRAIDE_LIMITS.titleMin &&
    titleLength <= ENTRAIDE_LIMITS.titleMax &&
    handleRead &&
    handleReady(handle, typed) &&
    !pending;

  async function publish() {
    if (!ready) {
      return;
    }
    setPending(true);
    setError(null);
    const result = await writeEntraide<{ id: number }>({
      action: "post",
      kind,
      title,
      body,
      handle: handle ? undefined : typed,
    });
    setPending(false);
    if (!result.ok) {
      setError(entraideErrorText(copy, result.error));
      return;
    }
    void hapticSuccess();
    // Cast while the typed routes are generated by the dev server.
    router.replace(`/entraide/${result.value.id}` as Href);
  }

  return (
    <Screen
      title={copy.hero.title}
      back={{ label: words.cancel, onPress: () => router.back() }}
      showRefresh={false}
      className="px-0 py-0"
    >
      <KeyboardAvoidingView
        className="flex-1"
        behavior={Platform.OS === "ios" ? "padding" : undefined}
        keyboardVerticalOffset={Platform.OS === "ios" ? 90 : 0}
      >
        <ScrollView
          keyboardShouldPersistTaps="handled"
          contentContainerClassName="gap-4 px-4 pb-16 pt-4"
          showsVerticalScrollIndicator={false}
        >
          <SegmentedControl
            label={words.kindLabel}
            segments={[
              { value: "question", label: copy.kinds.question },
              { value: "share", label: copy.kinds.share },
            ]}
            value={kind}
            onChange={setKind}
          />

          <View className="gap-2">
            <Text className="px-1 text-sm font-medium">
              {kind === "question" ? words.titleQuestion : words.titleShare}
            </Text>
            <Input
              value={title}
              onChangeText={setTitle}
              placeholder={words.titlePlaceholder}
              maxLength={ENTRAIDE_LIMITS.titleMax}
              accessibilityLabel={
                kind === "question" ? words.titleQuestion : words.titleShare
              }
              autoFocus
            />
          </View>

          {shownMatches.length > 0 ? (
            <Animated.View
              entering={
                reduceMotion ? undefined : FadeInDown.duration(DURATION.panel)
              }
              exiting={reduceMotion ? undefined : FadeOut.duration(DURATION.press)}
              className="gap-1.5 rounded-card border border-border bg-card/70 p-3"
            >
              <Text variant="label" className="px-1 pb-1">
                {words.already}
              </Text>
              {shownMatches.map((match, index) => (
                <Animated.View
                  key={match.id}
                  entering={
                    reduceMotion
                      ? undefined
                      : FadeInDown.duration(DURATION.panel).delay(
                          index * STAGGER_STEP_MS,
                        )
                  }
                >
                  <Pressable
                    accessibilityRole="link"
                    onPress={() => {
                      void hapticSelection();
                      // Cast while the typed routes are generated by the dev server.
                      router.push(`/entraide/${match.id}` as Href);
                    }}
                    className="min-h-11 flex-row items-center gap-3 rounded-control px-1 py-1.5 active:bg-foreground/5"
                  >
                    <View className="flex-1 gap-0.5">
                      <Text className="text-sm">{match.title}</Text>
                      <Text variant="muted" className="text-xs">
                        {match.solved
                          ? copy.list.solved
                          : match.replyCount > 0
                            ? countWords(copy.list.replies, match.replyCount)
                            : copy.list.noReply}
                      </Text>
                    </View>
                    <Ionicons
                      name="chevron-forward"
                      size={ICON.md}
                      color={colors.mutedForeground}
                    />
                  </Pressable>
                </Animated.View>
              ))}
            </Animated.View>
          ) : null}

          <View className="gap-2">
            <Text className="px-1 text-sm font-medium">{words.bodyLabel}</Text>
            <Input
              value={body}
              onChangeText={setBody}
              placeholder={words.bodyPlaceholder}
              maxLength={ENTRAIDE_LIMITS.bodyMax}
              multiline
              textAlignVertical="top"
              accessibilityLabel={words.bodyLabel}
              className="min-h-36"
            />
            <Text variant="muted" className="px-1 text-xs">
              {words.formatHint}
            </Text>
          </View>

          {handleRead && handle === null ? (
            <HandleField value={typed} onChange={setTyped} copy={copy} />
          ) : null}

          <MaskNotice text={`${title}\n${body}`} copy={copy} />

          {error ? (
            <Text accessibilityRole="alert" className="text-sm">
              {error}
            </Text>
          ) : null}

          <Button
            label={pending ? words.publishing : words.publish}
            size="lg"
            disabled={!ready}
            onPress={() => void publish()}
          />
          <Pressable
            accessibilityRole="link"
            disabled={!WEB_APP_URL}
            onPress={() =>
              void WebBrowser.openBrowserAsync(
                `${WEB_APP_URL}${ENTRAIDE_HREF}/regles`,
              )
            }
            className="min-h-11 justify-center"
          >
            <Text variant="muted" className="text-center text-xs">
              {words.agree}
            </Text>
          </Pressable>
        </ScrollView>
      </KeyboardAvoidingView>
    </Screen>
  );
}
