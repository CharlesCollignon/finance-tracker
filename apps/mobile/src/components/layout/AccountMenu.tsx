import { useState } from "react";
import { Modal, Pressable, View } from "react-native";
import { Ionicons } from "@expo/vector-icons";
import { useRouter, type Href } from "expo-router";

import { UserInitial } from "@/components/layout/UserInitial";
import { Text } from "@/components/ui/Text";
import { useAuth } from "@/providers/AuthProvider";
import { hapticLight } from "@/lib/haptics";
import { useNouveautes } from "@/lib/nouveautes";
import { cn } from "@/lib/cn";
import { useThemeColors } from "@/theme/useThemeColors";
import { ICON } from "@/theme/tokens";
import { useT } from "@/providers/LocaleProvider";

function initialFor(email: string | undefined, name: string | undefined) {
  const source = (name ?? email ?? "?").trim();
  return (source.charAt(0) || "?").toUpperCase();
}

/**
 * Header account control: monogram trigger opening a panel with a link to
 * Profile, « Nouveautés » and sign out — the mobile counterpart of the web
 * AccountMenu. While the account has changes it has not seen, the monogram
 * carries a dot in the status green and the row their count, as on the web.
 *
 * The theme toggle used to live here. Pluclair is dark now, with no light
 * palette to switch to.
 */
export function AccountMenu() {
  const t = useT();
  const { user, signOut } = useAuth();
  const router = useRouter();
  const colors = useThemeColors();
  const [open, setOpen] = useState(false);
  const { unseen } = useNouveautes(user?.id ?? null);

  const displayName =
    (user?.user_metadata?.full_name as string | undefined) ??
    (user?.user_metadata?.name as string | undefined);
  const initial = initialFor(user?.email, displayName);

  const rowClass =
    "min-h-11 w-full flex-row items-center gap-3 rounded-control px-3";

  return (
    <>
      <Pressable
        accessibilityRole="button"
        accessibilityLabel={
          unseen.length > 0
            ? `${t("common.accountMenu")}, ${t("nav.nouveautesUnseen", { count: unseen.length })}`
            : t("common.accountMenu")
        }
        hitSlop={6}
        onPress={() => {
          void hapticLight();
          setOpen(true);
        }}
        className="h-9 w-9 items-center justify-center rounded-control"
      >
        <UserInitial initial={initial} />
        {unseen.length > 0 ? (
          <View
            pointerEvents="none"
            className="absolute right-0.5 top-0.5 h-2.5 w-2.5 rounded-full border-2 border-background bg-success"
          />
        ) : null}
      </Pressable>

      <Modal
        visible={open}
        transparent
        animationType="fade"
        statusBarTranslucent
        onRequestClose={() => setOpen(false)}
      >
        <Pressable
          accessibilityLabel={t("common.closeAccountMenu")}
          className="flex-1 bg-black/25"
          onPress={() => setOpen(false)}
        >
          <View className="mt-16 items-end px-4">
            {/* Swallows taps so they do not close the sheet; not a control. */}
            <Pressable
              accessible={false}
              importantForAccessibility="no"
              onPress={(event) => event.stopPropagation()}
            >
              {/* Solid surface: the frosted panel made the rows hard to
                  read against busy content behind it. */}
              <View className="w-72 overflow-hidden rounded-card border border-border bg-card">
                <View className="gap-1 p-2">
                  <Pressable
                    accessibilityRole="link"
                    className={cn(rowClass)}
                    onPress={() => {
                      setOpen(false);
                      router.push("/profile");
                    }}
                  >
                    <Ionicons
                      name="settings-outline"
                      size={ICON.lg}
                      color={colors.foreground}
                    />
                    {/* The row goes to /profile, so it says what that surface
                        is called. "Settings" was a screen this app does not
                        have. */}
                    <Text className="text-sm font-medium">
                      {t("nav.profile")}
                    </Text>
                  </Pressable>

                  <Pressable
                    accessibilityRole="link"
                    className={cn(rowClass)}
                    onPress={() => {
                      setOpen(false);
                      // Cast while the typed routes are generated by the dev server.
                      router.push("/nouveautes" as Href);
                    }}
                  >
                    <Ionicons
                      name="newspaper-outline"
                      size={ICON.lg}
                      color={colors.foreground}
                    />
                    <Text className="flex-1 text-sm font-medium">
                      {t("nav.nouveautes")}
                    </Text>
                    {unseen.length > 0 ? (
                      <View
                        accessibilityLabel={t("nav.nouveautesUnseen", {
                          count: unseen.length,
                        })}
                        className="min-w-5 items-center rounded-full bg-success px-1.5 py-0.5"
                      >
                        <Text className="text-[10px] font-semibold text-success-foreground">
                          {unseen.length > 9 ? "9+" : unseen.length}
                        </Text>
                      </View>
                    ) : null}
                  </Pressable>

                  <Pressable
                    accessibilityRole="button"
                    className={cn(rowClass)}
                    onPress={() => {
                      setOpen(false);
                      void signOut();
                    }}
                  >
                    <Ionicons
                      name="log-out-outline"
                      size={ICON.lg}
                      color={colors.foreground}
                    />
                    <Text className="text-sm font-medium">
                      {t("common.signOut")}
                    </Text>
                  </Pressable>
                </View>
              </View>
            </Pressable>
          </View>
        </Pressable>
      </Modal>
    </>
  );
}
