import { useEffect, useState } from "react";
import { Modal, Pressable, View } from "react-native";
import { useRouter, type Href } from "expo-router";
import Animated, {
  useReducedMotion,
} from "react-native-reanimated";

import { changeText } from "@finance/core/changelog";

import { SheetGrabber } from "@/components/ui/SheetGrabber";
import { Text } from "@/components/ui/Text";
import { hapticLight } from "@/lib/haptics";
import {
  isFirstLaunchAfterUpdate,
  markNouveautesSeen,
  useNouveautes,
} from "@/lib/nouveautes";
import { useAuth } from "@/providers/AuthProvider";
import { useLocale, useT } from "@/providers/LocaleProvider";
import { FADE_IN } from "@/components/motion/fade";

/** How many changes the sheet lists before « Tout voir » takes over. */
const SHOWN = 4;

/**
 * « Quoi de neuf », once, on the first launch after the APK was updated: the
 * changes this account has not seen yet, fading in with a light haptic,
 * and « Tout voir » for the rest. Either button marks them
 * read, which clears the account menu's dot here and on the web. Nothing on
 * a first install, nothing when everything was already seen.
 */
export function WhatsNewSheet() {
  const t = useT();
  const locale = useLocale();
  const router = useRouter();
  const reduceMotion = useReducedMotion();
  const { user } = useAuth();
  const userId = user?.id ?? null;
  const { unseen, loaded } = useNouveautes(userId);
  const [updated, setUpdated] = useState(false);
  const [closed, setClosed] = useState(false);

  useEffect(() => {
    let cancelled = false;
    void isFirstLaunchAfterUpdate().then((first) => {
      if (!cancelled && first) {
        setUpdated(true);
      }
    });
    return () => {
      cancelled = true;
    };
  }, []);

  const visible = updated && loaded && !closed && unseen.length > 0 && !!userId;

  function close(thenSeeAll: boolean) {
    setClosed(true);
    if (userId) {
      void markNouveautesSeen(userId, locale);
    }
    if (thenSeeAll) {
      // Cast while the typed routes are generated by the dev server.
      router.push("/nouveautes" as Href);
    }
  }

  return (
    <Modal
      visible={visible}
      transparent
      animationType="fade"
      statusBarTranslucent
      onRequestClose={() => close(false)}
    >
      <Pressable
        accessibilityLabel={t("nouveautes.whatsNewClose")}
        className="flex-1 justify-end bg-black/40"
        onPress={() => close(false)}
      >
        <Pressable
          accessible={false}
          onPress={(event) => event.stopPropagation()}
          className="gap-3 rounded-t-card border border-border bg-card px-4 pb-10 pt-3"
        >
          <SheetGrabber />
          <Text variant="title">{t("nouveautes.whatsNewTitle")}</Text>
          <Text variant="muted">{t("nouveautes.whatsNewIntro")}</Text>
          {unseen.slice(0, SHOWN).map((entry) => {
            const text = changeText(entry, locale);
            return (
              <Animated.View
                key={entry.id}
                entering={reduceMotion ? undefined : FADE_IN}
                className="flex-row gap-3 rounded-card border border-border bg-background/40 p-3"
              >
                <View className="mt-1.5 h-2 w-2 rounded-full bg-success" />
                <View className="flex-1 gap-0.5">
                  <Text variant="head">{text.title}</Text>
                  <Text variant="muted">{text.body}</Text>
                </View>
              </Animated.View>
            );
          })}
          <View className="flex-row gap-2 pt-2">
            <Pressable
              accessibilityRole="link"
              onPress={() => {
                void hapticLight();
                close(true);
              }}
              className="min-h-11 flex-1 items-center justify-center rounded-full bg-foreground"
            >
              <Text className="text-sm font-semibold text-background">
                {t("nouveautes.whatsNewAll")}
              </Text>
            </Pressable>
            <Pressable
              accessibilityRole="button"
              onPress={() => close(false)}
              className="min-h-11 items-center justify-center rounded-full border border-border px-5"
            >
              <Text className="text-sm font-medium">
                {t("nouveautes.whatsNewClose")}
              </Text>
            </Pressable>
          </View>
        </Pressable>
      </Pressable>
    </Modal>
  );
}
