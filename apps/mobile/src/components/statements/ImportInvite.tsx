import { useEffect, useState } from "react";
import { Pressable, View } from "react-native";
import { useRouter, type Href } from "expo-router";
import { Ionicons } from "@expo/vector-icons";
import AsyncStorage from "@react-native-async-storage/async-storage";
import Animated, { useReducedMotion } from "react-native-reanimated";

import { Button } from "@/components/ui/Button";
import { Text } from "@/components/ui/Text";
import { cn } from "@/lib/cn";
import { hapticLight } from "@/lib/haptics";
import { useT } from "@/providers/LocaleProvider";
import { ICON } from "@/theme/tokens";
import { useThemeColors } from "@/theme/useThemeColors";
import { FADE_IN } from "@/components/motion/fade";

/** Where a dismissal is remembered: on this phone, as a convenience. */
const DISMISSED_KEY = "pluclair.importInvite.dismissed";

/**
 * The Journal's invitation to bring the bank's statement, for a ledger no
 * line has come into yet — the web's `ImportInvite`. Gone once a statement
 * is imported, or once waved away here.
 */
export function ImportInvite({ className }: { className?: string }) {
  const t = useT();
  const router = useRouter();
  const colors = useThemeColors();
  const reduceMotion = useReducedMotion();
  // Hidden until this phone says it was not waved away.
  const [shown, setShown] = useState(false);

  useEffect(() => {
    let live = true;
    void AsyncStorage.getItem(DISMISSED_KEY)
      .then((value) => {
        if (live) {
          setShown(value !== "1");
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, []);

  if (!shown) {
    return null;
  }

  return (
    <Animated.View
      entering={reduceMotion ? undefined : FADE_IN}
      className={cn("flex-row items-center gap-3 rounded-control border bg-primary/5 px-3 py-3", className)}
      style={{ borderColor: colors.primaryRim }}
    >
      <View className="h-8 w-8 items-center justify-center rounded-full bg-primary">
        <Ionicons name="document-attach-outline" size={ICON.md} color={colors.primaryForeground} />
      </View>
      <View className="flex-1 gap-0.5">
        <Text className="text-sm font-medium">{t("statements.inviteTitle")}</Text>
        <Text variant="muted" className="text-xs">
          {t("statements.inviteBody")}
        </Text>
        <View className="flex-row pt-2">
          <Button
            label={t("statements.heading")}
            size="sm"
            onPress={() =>
              // Cast while the typed routes are generated by the dev server.
              router.push("/import" as Href)
            }
          />
        </View>
      </View>
      <Pressable
        accessibilityRole="button"
        accessibilityLabel={t("statements.inviteDismiss")}
        hitSlop={8}
        onPress={() => {
          void hapticLight();
          setShown(false);
          void AsyncStorage.setItem(DISMISSED_KEY, "1").catch(() => undefined);
        }}
        className="h-9 w-9 items-center justify-center self-start rounded-full"
      >
        <Ionicons name="close" size={ICON.sm} color={colors.mutedForeground} />
      </Pressable>
    </Animated.View>
  );
}
